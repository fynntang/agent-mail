import {test} from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdir,mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {chromium,expect} from '@playwright/test';
import {createOwnerRuntime} from '../helpers/owner-runtime.mjs';
import {seedMessages} from '../helpers/mail-fixtures.mjs';

test('Owner outbound browser: scopes and policy, frozen approval, native send, Sent and explicit reply',{timeout:120_000},async t=>{
  const port=Number(process.env.OUTBOUND_E2E_PORT??4195),origin=`http://127.0.0.1:${port}`;
  const runtime=await createOwnerRuntime({consoleOrigin:origin,port});let browser;
  t.after(async()=>{await browser?.close();await runtime.mf.dispose();});
  const created=await runtime.request('/owner/api/mailboxes',{method:'POST',body:{name:'Outbound Agent',localPart:'outbound-agent'}});
  assert.equal(created.status,201,await created.clone().text());
  const box=(await created.json()).mailbox;
  const [source]=await seedMessages(runtime,box.id,{prefix:'需要回复的构建报告',text:'请回复这份构建报告。'});
  await runtime.db.prepare('UPDATE messages SET rfc_message_id=? WHERE id=?').bind('<browser-reply@example.net>',source.id).run();
  await runtime.mf.ready;
  const channel=process.env.PLAYWRIGHT_CHANNEL??(process.platform==='win32'?(existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe')?'chrome':'msedge'):undefined);
  browser=await chromium.launch({headless:true,...(channel?{channel}:{})});
  const context=await browser.newContext({viewport:{width:1488,height:1056},extraHTTPHeaders:{'Cf-Access-Jwt-Assertion':runtime.jwt}});
  const page=await context.newPage(),errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(['error','warning'].includes(message.type()))errors.push(message.text());});
  page.on('request',request=>{if(new URL(request.url()).origin!==origin)external.push(request.url());});
  const mailboxPath=`${origin}/owner/mailboxes/${box.id}`;

  await page.goto(mailboxPath);
  // A visible SSR input can precede client hydration. Opening/closing a real dialog
  // proves the settings component is interactive before editing numeric bindings.
  const readiness=page.getByRole('dialog',{name:'签发 Token',exact:true});
  await expect.poll(async()=>{
    if(await readiness.isVisible())return true;
    await page.getByRole('button',{name:'签发 Token',exact:true}).click();
    return readiness.isVisible();
  }).toBe(true);
  await readiness.getByRole('button',{name:'取消',exact:true}).click();
  await expect(readiness).not.toBeVisible();
  const dailyLimit=page.getByLabel('每日收件人数上限',{exact:true});
  await dailyLimit.fill('25');await expect(dailyLimit).toHaveValue('25');
  await page.getByLabel('允许的收件人',{exact:true}).fill('recipient@example.net\ncopy@example.net\nhidden@example.net');
  await page.getByRole('button',{name:'保存更改',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('邮箱设置已保存。');
  assert.equal(await runtime.db.prepare('SELECT daily_recipient_limit FROM mailboxes WHERE id=?').bind(box.id).first('daily_recipient_limit'),25);
  await page.getByRole('button',{name:'签发 Token',exact:true}).click();
  const issue=page.getByRole('dialog',{name:'签发 Token',exact:true});
  await issue.getByLabel('名称',{exact:true}).fill('Sender Agent');
  await issue.getByRole('checkbox',{name:/^请求发信/}).check();
  await expect(issue.getByRole('checkbox',{name:/^草稿编辑/})).toBeChecked();
  await expect(issue.getByRole('checkbox',{name:/^草稿编辑/})).toBeDisabled();
  await expect(issue.getByRole('checkbox',{name:'发信需要 Owner 逐封审批',exact:true})).toBeChecked();
  await issue.getByRole('button',{name:'签发 Token',exact:true}).click();
  const secretDialog=page.getByRole('dialog',{name:'Token 已签发',exact:true});
  await expect(secretDialog).toBeVisible();
  const secret=await secretDialog.getByLabel('完整 Token',{exact:true}).inputValue();
  await secretDialog.getByRole('button',{name:'我已保存',exact:true}).click();
  const token=await runtime.db.prepare('SELECT can_read,can_draft,can_send,requires_approval FROM mailbox_tokens WHERE mailbox_id=?').bind(box.id).first();
  assert.deepEqual(token,{can_read:1,can_draft:1,can_send:1,requires_approval:1});
  assert.equal((await page.content()).includes(secret),false);

  await page.getByRole('navigation',{name:'邮箱功能'}).getByRole('link',{name:'草稿与发信',exact:true}).click();
  await expect(page).toHaveTitle('Outbound Agent · 草稿与发信 · Agent Mail');
  await expect(page.getByRole('heading',{name:'新邮件',exact:true})).toBeVisible();
  await expect(page.getByText('正在读取草稿…',{exact:true})).toHaveCount(0);
  await page.getByLabel('收件人',{exact:true}).fill('recipient@example.net');
  await page.getByLabel('抄送',{exact:true}).fill('copy@example.net');
  await page.getByLabel('密送',{exact:true}).fill('hidden@example.net');
  await page.getByLabel('主题',{exact:true}).fill('经过核对的发信测试');
  const initialText='你好，\n\n这是正文 <script>globalThis.__outboundXss=true</script>。\n请核对所有收件人。';
  const finalText=initialText+'\n版本修改后必须重新审批。';
  await page.getByLabel('文本正文',{exact:true}).fill(initialText);
  await page.getByRole('button',{name:'保存草稿',exact:true}).click();
  const preview=page.getByRole('region',{name:'核对与审批',exact:true});
  await expect(preview).toBeVisible();
  await expect(preview.locator('dd').filter({hasText:'hidden@example.net'})).toBeVisible();
  await expect(preview.locator('.approval-body')).toHaveText(initialText);
  await expect(preview.locator('code')).toHaveText(/^[0-9a-f]{64}$/);
  assert.equal(await preview.locator('script,img,iframe').count(),0);
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'审批当前版本',exact:true}).click();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeEnabled();
  assert.equal(await runtime.db.prepare('SELECT count(*) FROM outbound_messages').first('count(*)'),0,'approval alone does not send');
  await page.getByLabel('文本正文',{exact:true}).fill(finalText);
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'保存新版本',exact:true}).click();
  await expect(preview.locator('.approval-body')).toHaveText(finalText);
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeDisabled();
  const saved=await runtime.db.prepare('SELECT id,version,state,approved_version,approved_sha256 FROM drafts WHERE mailbox_id=?').bind(box.id).first();
  assert.equal(saved.version,2);assert.equal(saved.state,'editing');assert.equal(saved.approved_version,null);assert.equal(saved.approved_sha256,null);
  await page.getByRole('button',{name:'审批当前版本',exact:true}).click();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'提交发送',exact:true}).click();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeDisabled();
  await expect(page.getByRole('region',{name:'发送记录',exact:true}).getByText('排队中',{exact:true})).toBeVisible();
  assert.equal(await runtime.db.prepare('SELECT count(*) FROM outbound_messages').first('count(*)'),1);
  const worker=await runtime.mf.getWorker();assert.equal((await worker.scheduled()).outcome,'ok');
  await page.getByRole('button',{name:'刷新',exact:true}).click();
  await expect(page.getByRole('region',{name:'发送记录',exact:true}).getByText('已接受（非送达）',{exact:true})).toBeVisible();
  await worker.scheduled();
  assert.equal(await runtime.db.prepare('SELECT count(*) FROM send_attempts').first('count(*)'),1);
  assert.equal(await page.evaluate(()=>globalThis.__outboundXss),undefined);
  const storage=await page.evaluate(()=>`${JSON.stringify(localStorage)}${JSON.stringify(sessionStorage)}`);
  assert.equal(storage.includes(secret),false);assert.equal(storage.includes(finalText),false);

  const directory=process.env.OUTBOUND_QA_DIR??await mkdtemp(join(tmpdir(),'agent-mail-outbound-qa-'));
  await mkdir(directory,{recursive:true});await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:join(directory,'outbound-desktop.png'),fullPage:true});
  await page.getByRole('navigation',{name:'邮箱功能'}).getByRole('link',{name:'邮件',exact:true}).click();
  await page.getByLabel('文件夹',{exact:true}).selectOption('sent');
  const reader=page.getByRole('region',{name:'邮件正文',exact:true});
  await expect(reader.getByRole('heading',{level:2})).toHaveText('经过核对的发信测试');
  await expect(reader.locator('.message-body')).toHaveText(finalText);
  assert.equal(await reader.locator('script,img,iframe').count(),0);

  await page.setViewportSize({width:390,height:844});
  await page.goto(`${mailboxPath}/messages?message=${source.id}`);
  await expect(reader.getByRole('heading',{level:2})).toHaveText(source.subject);
  const draftCount=await runtime.db.prepare('SELECT count(*) FROM drafts').first('count(*)');
  await reader.getByRole('link',{name:'回复',exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`/outbound\\?reply=${source.id}$`));
  await expect(page.getByRole('button',{name:'创建回复草稿',exact:true})).toBeVisible();
  await expect(page.getByText('正在读取草稿…',{exact:true})).toHaveCount(0);
  assert.equal(await runtime.db.prepare('SELECT count(*) FROM drafts').first('count(*)'),draftCount,'opening a reply link does not create a draft');
  await page.getByRole('button',{name:'创建回复草稿',exact:true}).click();
  await expect(page.getByLabel('收件人',{exact:true})).toHaveValue('build@example.net');
  await expect(page.getByLabel('主题',{exact:true})).toHaveValue(`Re: ${source.subject}`);
  await expect(preview.getByText('<browser-reply@example.net>',{exact:true})).toBeVisible();
  assert.equal(await runtime.db.prepare('SELECT count(*) FROM drafts').first('count(*)'),draftCount+1);
  assert.equal(await runtime.db.prepare('SELECT is_read FROM messages WHERE id=?').bind(source.id).first('is_read'),0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile compose page must not overflow');
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:join(directory,'outbound-mobile.png'),fullPage:true});
  assert.equal(await page.locator('vite-error-overlay').count(),0);assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log(`Outbound browser QA passed: ${origin}, desktop 1488x1056 / mobile 390x844; screenshots: ${directory}`);
});
