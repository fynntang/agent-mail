import {test} from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdir,mkdtemp,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {chromium,expect} from '@playwright/test';
import {createOwnerRuntime} from '../helpers/owner-runtime.mjs';

test('Owner sends draft attachments: upload, review, edit/delete invalidate approval and Sent keeps exact bytes',{timeout:120_000},async t=>{
  const port=Number(process.env.OUTBOUND_ATTACHMENTS_E2E_PORT??4199),origin=`http://127.0.0.1:${port}`;
  const runtime=await createOwnerRuntime({consoleOrigin:origin,port});let browser;
  t.after(async()=>{await browser?.close();await runtime.mf.dispose();});
  const created=await runtime.request('/owner/api/mailboxes',{method:'POST',body:{name:'附件发送 Agent',localPart:'attachment-sender'}});
  assert.equal(created.status,201,await created.clone().text());const box=(await created.json()).mailbox;
  const issued=await runtime.request(`/owner/api/mailboxes/${box.id}/tokens`,{method:'POST',body:{name:'Draft Attachment Agent',scopes:['mail:draft','mail:send']}});
  assert.equal(issued.status,201);const {secret}=await issued.json();
  const newDraft=await runtime.mf.dispatchFetch('https://api.example.com/v1/drafts',{method:'POST',headers:{Authorization:`Bearer ${secret}`,'Content-Type':'application/json'},
    body:JSON.stringify({to:['recipient@example.net'],bcc:['hidden@example.net'],subject:'发送附件审查',text:'请核对附件及所有收件人。'})});
  assert.equal(newDraft.status,201,await newDraft.clone().text());const initial=(await newDraft.json()).draft;
  assert.ok(initial.createdByTokenId);
  await runtime.mf.ready;
  const channel=process.env.PLAYWRIGHT_CHANNEL??(process.platform==='win32'?(existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe')?'chrome':'msedge'):undefined);
  browser=await chromium.launch({headless:true,...(channel?{channel}:{})});
  const context=await browser.newContext({viewport:{width:1488,height:1056},acceptDownloads:true,extraHTTPHeaders:{'Cf-Access-Jwt-Assertion':runtime.jwt}});
  const page=await context.newPage(),errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(['error','warning'].includes(message.type()))errors.push(message.text());});
  page.on('request',request=>{if(new URL(request.url()).origin!==origin)external.push(request.url());});
  const base=`${origin}/owner/mailboxes/${box.id}`;
  await page.goto(`${base}/outbound`);
  await expect(page).toHaveTitle('附件发送 Agent · 草稿与发信 · Agent Mail');
  await expect(page.getByRole('heading',{level:1})).toHaveText('附件发送 Agent');
  await page.locator('.draft-list button').filter({hasText:'发送附件审查'}).click();
  const preview=page.getByRole('region',{name:'核对与审批',exact:true});
  const attachments=page.getByRole('region',{name:'草稿附件',exact:true});
  await expect(preview).toBeVisible();await expect(attachments).toContainText('此版本没有附件');
  await page.getByRole('button',{name:'审批当前版本',exact:true}).click();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeEnabled();

  const binary=Buffer.from([0,1,2,127,128,200,254,255,13,10,42]);
  const removable=Buffer.from('这个文件将在发送前移除。','utf8');
  const chooserPromise=page.waitForEvent('filechooser');
  await attachments.getByRole('button',{name:'添加附件',exact:true}).click();
  const chooser=await chooserPromise;
  await chooser.setFiles([{name:'资料_二进制.bin',mimeType:'application/octet-stream',buffer:binary},{name:'remove.txt',mimeType:'text/plain',buffer:removable}]);
  await expect(attachments.locator('.draft-attachment-list>li')).toHaveCount(2);
  await expect(attachments.getByRole('button',{name:'添加附件',exact:true})).toBeEnabled();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeDisabled();
  const current=async()=>{
    const response=await runtime.request(`/owner/api/mailboxes/${box.id}/drafts/${initial.id}`);assert.equal(response.status,200);return (await response.json()).draft;
  };
  let saved=await current();assert.equal(saved.version,3);assert.equal(saved.state,'editing');assert.equal(saved.content.attachments.length,2);
  const binaryRef=saved.content.attachments.find(value=>value.filename==='资料_二进制.bin');
  assert.equal(binaryRef.sha256,createHash('sha256').update(binary).digest('hex'));
  const binaryRow=attachments.locator('.draft-attachment-list>li').filter({hasText:'资料_二进制.bin'});
  await expect(binaryRow.locator('code')).toHaveText(binaryRef.sha256);
  const downloadPromise=page.waitForEvent('download');
  await binaryRow.getByRole('link',{name:'下载草稿附件 资料_二进制.bin',exact:true}).click();
  const download=await downloadPromise;assert.equal(await download.failure(),null);assert.equal(download.suggestedFilename(),'资料_二进制.bin');
  assert.deepEqual(await readFile(await download.path()),binary);
  await page.getByRole('button',{name:'审批当前版本',exact:true}).click();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeEnabled();

  const directory=process.env.OUTBOUND_ATTACHMENTS_QA_DIR??await mkdtemp(join(tmpdir(),'agent-mail-outbound-attachments-qa-'));
  await mkdir(directory,{recursive:true});await attachments.scrollIntoViewIfNeeded();
  await page.screenshot({path:join(directory,'outbound-attachments-desktop.png'),fullPage:false});
  await page.setViewportSize({width:390,height:844});await attachments.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Attachment names and hashes must wrap on mobile');
  await page.screenshot({path:join(directory,'outbound-attachments-mobile.png'),fullPage:false});

  await page.getByLabel('文本正文',{exact:true}).fill('修改正文后，附件应保持不变。');
  await expect(attachments.getByRole('button',{name:'添加附件',exact:true})).toBeDisabled();
  await expect(attachments.getByRole('button',{name:'移除附件 remove.txt',exact:true})).toBeDisabled();
  await expect(attachments).toContainText('请先保存文本更改');
  await page.getByRole('button',{name:'保存新版本',exact:true}).click();
  await expect(attachments.getByRole('button',{name:'添加附件',exact:true})).toBeEnabled();
  saved=await current();assert.equal(saved.version,4);assert.equal(saved.state,'editing');assert.equal(saved.content.attachments.length,2);
  assert.equal(saved.content.attachments.find(value=>value.id===binaryRef.id).sha256,binaryRef.sha256);
  await page.getByRole('button',{name:'审批当前版本',exact:true}).click();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeEnabled();
  await attachments.getByRole('button',{name:'移除附件 remove.txt',exact:true}).click();
  await expect(attachments.locator('.draft-attachment-list>li')).toHaveCount(1);
  await expect(attachments.getByRole('button',{name:'添加附件',exact:true})).toBeEnabled();
  await expect(page.getByRole('button',{name:'提交发送',exact:true})).toBeDisabled();
  saved=await current();assert.equal(saved.version,5);assert.equal(saved.state,'editing');assert.equal(saved.content.attachments[0].id,binaryRef.id);
  const dbDraft=await runtime.db.prepare('SELECT approved_version,approved_sha256 FROM drafts WHERE id=?').bind(initial.id).first();
  assert.deepEqual(dbDraft,{approved_version:null,approved_sha256:null});
  await page.getByRole('button',{name:'审批当前版本',exact:true}).click();
  await page.getByRole('button',{name:'提交发送',exact:true}).click();
  const history=page.getByRole('region',{name:'发送记录',exact:true});
  await expect(history.getByText('排队中',{exact:true})).toBeVisible();
  await expect(attachments.getByRole('button',{name:'添加附件',exact:true})).toHaveCount(0);
  const worker=await runtime.mf.getWorker();assert.equal((await worker.scheduled()).outcome,'ok');
  await page.getByRole('button',{name:'刷新',exact:true}).click();
  await expect(history.getByText('已接受（非送达）',{exact:true})).toBeVisible();
  await worker.scheduled();assert.equal(await runtime.db.prepare('SELECT count(*) n FROM send_attempts').first('n'),1);
  const sent=await runtime.db.prepare("SELECT id,raw_object_id FROM messages WHERE mailbox_id=? AND direction='outbound'").bind(box.id).first();assert.ok(sent);
  const detail=await (await runtime.request(`/owner/api/mailboxes/${box.id}/messages/${sent.id}`)).json();
  assert.equal(detail.attachments.status,'ready');assert.equal(detail.attachments.attachments.length,1);assert.equal(detail.attachments.attachments[0].filename,binaryRef.filename);
  await page.goto(`${base}/messages?folder=sent&message=${sent.id}`);
  const sentAttachments=page.getByRole('region',{name:'邮件附件',exact:true});
  await expect(sentAttachments).toContainText('资料_二进制.bin');await expect(sentAttachments).not.toContainText('remove.txt');
  const sentDownloadPromise=page.waitForEvent('download');await sentAttachments.getByRole('link',{name:'下载 资料_二进制.bin',exact:true}).click();
  const sentDownload=await sentDownloadPromise;assert.equal(await sentDownload.failure(),null);assert.deepEqual(await readFile(await sentDownload.path()),binary);
  const raw=await runtime.db.prepare('SELECT object_key FROM objects WHERE id=?').bind(sent.raw_object_id).first();
  const eml=await (await runtime.bucket.get(raw.object_key)).text();assert.match(eml,/multipart\/mixed/);assert.equal(/^Bcc:/im.test(eml),false);
  assert.equal((await page.content()).includes(secret),false);assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  assert.equal(await page.locator('vite-error-overlay').count(),0);
  console.log(`Draft attachment browser QA passed: ${origin}, desktop 1488x1056 / mobile 390x844; screenshots: ${directory}`);
});
