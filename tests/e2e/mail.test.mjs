import {test} from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdir,mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {chromium,expect} from '@playwright/test';
import {createOwnerRuntime} from '../helpers/owner-runtime.mjs';
import {seedMessages} from '../helpers/mail-fixtures.mjs';

test('mail reader: mailbox isolation, safe body, explicit read state, filters, paging and mobile navigation',{timeout:120_000},async t=>{
  const port=Number(process.env.OWNER_E2E_PORT??4194),origin=`http://127.0.0.1:${port}`;
  const runtime=await createOwnerRuntime({consoleOrigin:origin,port});let browser;
  t.after(async()=>{await browser?.close();await runtime.mf.dispose();});
  async function create(name,localPart){return (await (await runtime.request('/owner/api/mailboxes',{method:'POST',body:{name,localPart}})).json()).mailbox;}
  const research=await create('Research','research'),assistant=await create('Assistant','assistant');
  const at=Date.now();
  const messages=await seedMessages(runtime,research.id,{count:23,prefix:'构建检查',receivedAt:at});
  const [privateMessage]=await seedMessages(runtime,assistant.id,{prefix:'Assistant 私有通知',text:'ASSISTANT_PRIVATE_BODY'});
  const [unsafe]=await seedMessages(runtime,research.id,{prefix:'安全检查 <img src=x onerror=globalThis.__mailXss=true>',
    receivedAt:at+1000,text:'<script>globalThis.__mailXss=true</script>\n<img src="https://tracking.invalid/pixel" onerror="alert(1)">\n邮件中的标签只是文本。'});
  await runtime.mf.ready;
  const channel=process.env.PLAYWRIGHT_CHANNEL??(process.platform==='win32'?(existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe')?'chrome':'msedge'):undefined);
  browser=await chromium.launch({headless:true,...(channel?{channel}:{})});
  const context=await browser.newContext({viewport:{width:1488,height:1056},extraHTTPHeaders:{'Cf-Access-Jwt-Assertion':runtime.jwt}});
  const page=await context.newPage(),errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(['error','warning'].includes(message.type()))errors.push(message.text());});
  page.on('request',request=>{if(new URL(request.url()).hostname==='tracking.invalid')external.push(request.url());});
  const base=`${origin}/owner/mailboxes/${research.id}/messages`;
  const list=page.getByRole('region',{name:'邮件列表',exact:true});
  const reader=page.getByRole('region',{name:'邮件正文',exact:true});
  await page.goto(base);
  await expect(page).toHaveTitle('Research · 邮件 · Agent Mail');
  await expect(page.getByRole('heading',{level:1})).toHaveText('Research');
  await expect(list.locator('.mail-items>li')).toHaveCount(20);
  await expect(reader.locator('.message-body')).toContainText('<script>globalThis.__mailXss=true</script>');
  assert.equal(await reader.locator('.message-body script,.message-body img,.message-body iframe').count(),0);
  assert.equal(await page.evaluate(()=>globalThis.__mailXss),undefined);assert.deepEqual(external,[]);
  assert.equal((await page.content()).includes('ASSISTANT_PRIVATE_BODY'),false);
  assert.equal(await runtime.db.prepare('SELECT is_read FROM messages WHERE id=?').bind(unsafe.id).first('is_read'),0);
  await list.locator(`a.mail-summary[href*="message=${messages[1].id}"]`).click();
  await expect(reader.getByRole('heading',{level:2})).toHaveText(messages[1].subject);
  await reader.getByRole('button',{name:'标记为已读',exact:true}).click();
  await expect(reader.getByRole('button',{name:'标记为未读',exact:true})).toBeVisible();
  assert.equal(await runtime.db.prepare('SELECT is_read FROM messages WHERE id=?').bind(messages[1].id).first('is_read'),1);
  const filter=page.getByRole('group',{name:'阅读状态筛选'});
  await filter.getByRole('button',{name:'已读',exact:true}).click();
  await expect(list.locator('.mail-items>li')).toHaveCount(1);
  await reader.getByRole('button',{name:'标记为未读',exact:true}).click();
  await expect(list.locator('.mail-items>li')).toHaveCount(0);
  await expect(reader.getByRole('heading',{level:2})).toHaveText(messages[1].subject);
  await expect(reader.getByText('此邮件已不在当前页或筛选结果中，正文仍保留在阅读区。')).toBeVisible();
  await expect(list.getByRole('link',{name:'返回第一页'})).toBeVisible();
  await filter.getByRole('button',{name:'全部',exact:true}).click();
  await page.getByRole('navigation',{name:'邮件分页'}).getByRole('link',{name:'下一页',exact:true}).click();
  await expect(list.locator('.mail-items>li')).toHaveCount(4);
  const cursor=new URL(page.url()).searchParams.get('cursor');assert.ok(cursor);
  await list.locator(`a.mail-summary[href*="message=${messages[22].id}"]`).click();
  await expect(reader.getByRole('heading',{level:2})).toHaveText(messages[22].subject);
  assert.equal(new URL(page.url()).searchParams.get('cursor'),cursor);await expect(list.locator('.mail-items>li')).toHaveCount(4);
  await page.getByRole('navigation',{name:'邮件分页'}).getByRole('link',{name:'上一页',exact:true}).click();
  await expect(list.locator('.mail-items>li')).toHaveCount(20);
  await page.getByLabel('每页封数',{exact:true}).selectOption('10');
  await expect(list.locator('.mail-items>li')).toHaveCount(10);assert.equal(new URL(page.url()).searchParams.has('cursor'),false);
  await page.getByLabel('文件夹',{exact:true}).selectOption('archive');
  await expect(list.getByRole('heading',{name:'没有符合条件的邮件'})).toBeVisible();
  await list.getByRole('link',{name:'返回第一页'}).click();
  await expect(list.getByRole('heading',{name:'没有符合条件的邮件'})).toBeVisible();
  await page.getByLabel('文件夹',{exact:true}).selectOption('inbox');

  const [missing]=await seedMessages(runtime,research.id,{prefix:'暂不可用的邮件',receivedAt:at+2000});
  await runtime.bucket.delete(missing.bodyKey);
  await page.goto(`${base}?message=${missing.id}`);
  await expect(reader.getByRole('alert')).toContainText('正文暂不可用');
  await reader.getByRole('button',{name:'重新加载正文'}).click();
  await expect(reader.getByRole('alert')).toContainText('正文暂不可用');
  const [notExtracted]=await seedMessages(runtime,research.id,{prefix:'尚未提取文本',receivedAt:at+3000,text:null});
  await page.goto(`${base}?message=${notExtracted.id}`);
  await expect(reader.getByRole('status')).toContainText('尚未提取可显示的文本正文');
  await runtime.db.prepare("UPDATE messages SET folder='spam' WHERE id IN(?,?,?)").bind(unsafe.id,missing.id,notExtracted.id).run();

  const nav=page.getByRole('navigation',{name:'邮箱列表'});
  await nav.locator(`a[href="/owner/mailboxes/${assistant.id}/messages"]`).click();
  await expect(reader.locator('.message-body')).toHaveText(privateMessage.text);
  await nav.locator(`a[href="/owner/mailboxes/${research.id}/messages"]`).click();
  await page.goto(`${base}?message=${messages[1].id}`);
  await expect(reader.getByRole('heading',{level:2})).toHaveText(messages[1].subject);
  await page.reload();await expect(reader.locator('.message-body')).toHaveText(messages[1].text);
  const directory=process.env.MAIL_QA_DIR??await mkdtemp(join(tmpdir(),'agent-mail-reader-qa-'));
  await mkdir(directory,{recursive:true});await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:join(directory,'mail-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await list.locator(`a.mail-summary[href*="message=${messages[4].id}"]`).click();
  await expect(page).toHaveURL(/#message-body$/);
  await expect(reader.getByRole('heading',{level:2})).toHaveText(messages[4].subject);
  await expect(reader).toBeInViewport();
  await reader.getByRole('button',{name:'标记为已读',exact:true}).click();
  await expect(reader.getByRole('button',{name:'标记为未读',exact:true})).toBeVisible();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:join(directory,'mail-mobile.png'),fullPage:true});
  assert.equal(await page.locator('vite-error-overlay').count(),0);assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log(`Mail browser QA passed: ${origin}, desktop 1488x1056 / mobile 390x844; screenshots: ${directory}`);
});
